# ========== Tool registry for dynamic tool discovery and management. ==========


import importlib
import inspect
from pathlib import Path


class ToolRegistry:
    """Registry for discovering and managing tools."""

    def __init__(self):
        self._tools: dict[str, MCPTool] = {}
        self._tool_classes: dict[str, type[MCPTool]] = {}

    def discover_tools(self, tools_path: Path | None = None) -> None:
        """Discover and register all tools in the tools directory."""
        if tools_path is None:
            # Default to the tools package
            tools_path = Path(__file__).parent.parent / "tools"

        logger.info(f"Discovering tools in {tools_path}")

        # Get all Python files in the tools directory
        tool_files = list(tools_path.glob("*.py"))
        logger.debug(f"Found {len(tool_files)} Python files in {tools_path}")

        for tool_file in tool_files:
            if tool_file.name.startswith("_") or tool_file.name == "base.py":
                continue

            # Try both import paths
            module_names = [
                f"council.tools.{tool_file.stem}",
                f"src.council.tools.{tool_file.stem}",
            ]

            module = None
            for module_name in module_names:
                try:
                    logger.debug(f"Attempting to import {module_name}")
                    module = importlib.import_module(module_name)
                    break
                except ImportError:
                    continue

            if module is None:
                logger.error(f"Failed to import tool from {tool_file}")
                continue

            try:
                # Concrete tools defined in this module, not ones it imports
                for name, obj in inspect.getmembers(module, inspect.isclass):
                    if (
                        issubclass(obj, MCPTool)
                        and not inspect.isabstract(obj)
                        and obj.__module__ == module.__name__
                    ):
                        logger.debug(f"Found tool class: {name}")
                        self._register_tool_class(obj)

            except Exception as e:
                logger.error(f"Failed to import tool from {tool_file}: {e}")

    def _register_tool_class(self, tool_class: type[MCPTool]) -> None:
        """Register a tool class."""
        try:
            # Instantiate the tool to get its metadata
            tool_instance = tool_class()
            # Use property-based access for compatibility
            tool_name = tool_instance.name

            if tool_name in self._tools:
                logger.warning(f"Tool {tool_name} already registered, skipping")
                return

            self._tools[tool_name] = tool_instance
            self._tool_classes[tool_name] = tool_class
            logger.info(f"Registered tool: {tool_name}")

        except Exception as e:
            logger.error(f"Failed to register tool {tool_class.__name__}: {e}")

    def get_tool(self, name: str) -> MCPTool | None:
        """Get a tool instance by name."""
        return self._tools.get(name)

    def get_tool_class(self, name: str) -> type[MCPTool] | None:
        """Get a tool class by name."""
        return self._tool_classes.get(name)

    def list_tools(self) -> list[str]:
        """List all registered tool names."""
        return list(self._tools.keys())

    def get_all_tools(self) -> dict[str, MCPTool]:
        """Get all registered tools."""
        return self._tools.copy()

    def get_mcp_tool_definitions(self) -> list[dict]:
        """Get MCP tool definitions for all registered tools."""
        definitions = []
        for tool in self._tools.values():
            try:
                definitions.append(tool.get_mcp_definition())
            except Exception as e:
                # Use property-based access for error logging
                tool_name = getattr(tool, "name", tool.__class__.__name__)
                logger.error(f"Failed to get MCP definition for {tool_name}: {e}")
        return definitions


# ========== Orchestrator: runs tools, caches results that may be reused, and counts execu... ==========


import time
from typing import Any


class ConversationOrchestrator:
    """Runs tools for the server, with caching and execution counts."""

    def __init__(
        self,
        tool_registry: ToolRegistry,
        model_manager: Any,
        cache: ResponseCache | None = None,
    ):
        self.tool_registry = tool_registry
        self.model_manager = model_manager
        self.cache = cache or ResponseCache()
        self.total_executions = 0
        self.successful_executions = 0
        self.total_execution_ms = 0.0

    async def execute_tool(
        self, tool_name: str, parameters: dict[str, Any], request_id: str | None = None
    ) -> ToolOutput:
        """Execute a single tool, serving a cached result when the tool allows it."""
        tool = self.tool_registry.get_tool(tool_name)
        if not tool:
            output = ToolOutput(success=False, error=f"Unknown tool: {tool_name}")
            output.tool_name = tool_name
            return output

        cache_key = self._cache_key(tool, tool_name, parameters)
        if cache_key:
            cached_result = self.cache.get(cache_key)
            if cached_result:
                logger.info(f"Cache hit for {tool_name}")
                return cached_result

        started = time.monotonic()
        output = await tool.execute(parameters)
        output.execution_time_ms = (time.monotonic() - started) * 1000

        # A tool can veto caching one result, e.g. a partial one
        if cache_key and output.success and output.metadata.get("cacheable", True):
            self.cache.set(cache_key, output)

        self.total_executions += 1
        if output.success:
            self.successful_executions += 1
        self.total_execution_ms += output.execution_time_ms

        return output

    def _cache_key(self, tool: Any, tool_name: str, parameters: dict[str, Any]) -> str | None:
        """The cache key for this call, or None when the result must not be cached.

        The key names the model that will answer, so switching the active
        model never serves the previous model's answer.
        """
        if not tool.is_cacheable(parameters):
            return None
        model = parameters.get("model") or getattr(self.model_manager, "active_model", None)
        return self.cache.create_key(tool_name, {"parameters": parameters, "model": model})

    def get_execution_stats(self) -> dict[str, Any]:
        """Get statistics about tool executions."""
        total = self.total_executions
        successful = self.successful_executions
        failed = total - successful
        avg_time = self.total_execution_ms / total if total else 0.0

        return {
            "total_executions": total,
            "successful": successful,
            "failed": failed,
            "success_rate": successful / total if total > 0 else 0,
            "average_execution_time_ms": avg_time,
            "cache_stats": self.cache.get_stats(),
        }


# ========== Load API keys stored as systemd user credentials.  Each key lives in `<direct... ==========


import os
import re
import subprocess
from pathlib import Path


CREDENTIAL_NAME_PATTERN = re.compile(r"^[A-Z][A-Z0-9_]*$")
DECRYPT_TIMEOUT_SECONDS = 20


def load_credentials(directory: str) -> list[str]:
    """Decrypt each NAME.cred in directory into os.environ[NAME].

    A variable that is already set wins, so an explicit environment override
    still works. Failures are logged and skipped; values are never logged.

    Args:
        directory: Directory holding the .cred files.

    Returns:
        Names of the variables that were loaded.
    """
    credential_dir = Path(directory)
    if not credential_dir.is_dir():
        return []

    loaded = []
    for path in sorted(credential_dir.glob("*.cred")):
        name = path.stem
        if not CREDENTIAL_NAME_PATTERN.match(name):
            logger.warning(f"Skipping credential with invalid name: {path.name}")
            continue
        if name in os.environ:
            logger.info(f"{name} already set in the environment; skipping its credential")
            continue

        try:
            # stdin is the MCP server's JSON-RPC channel: keep the child off it
            result = subprocess.run(
                ["systemd-creds", "decrypt", "--user", f"--name={name}", str(path), "-"],
                stdin=subprocess.DEVNULL,
                capture_output=True,
                timeout=DECRYPT_TIMEOUT_SECONDS,
            )
        except (OSError, subprocess.TimeoutExpired) as e:
            logger.warning(f"Could not run systemd-creds for {name}: {e}")
            continue

        if result.returncode != 0:
            error = result.stderr.decode(errors="replace").strip()
            logger.warning(f"Could not decrypt credential {name}: {error}")
            continue

        try:
            value = result.stdout.decode().strip()
        except UnicodeDecodeError:
            logger.warning(f"Credential {name} is not valid UTF-8; skipping it")
            continue
        os.environ[name] = value
        loaded.append(name)

    if loaded:
        logger.info(f"Loaded credentials: {', '.join(loaded)}")
    return loaded


